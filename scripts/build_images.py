#!/usr/bin/env python3
"""Prepare photos for the site.

For every JPG/PNG photo under assets/images/products/, assets/images/content/ and
assets/images/instagram/ this writes WebP copies at several widths next to the original and records the original size
in _data/images.yml. The templates (_includes/img.html) use that file to add width,
height and a srcset, so browsers download a size that fits the screen.

Run it after adding or replacing photos:

    python3 scripts/build_images.py

Requires Pillow (pip install Pillow). Originals are never changed.
"""
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent
PHOTO_DIRS = ["assets/images/products", "assets/images/content", "assets/images/instagram"]
# Files that only need their size recorded (no resized copies).
SIZE_ONLY = ["assets/images/meta.jpg"]
WIDTHS = [480, 800, 1200, 1600]
QUALITY = 80


def variants_for(path: Path):
    with Image.open(path) as source:
        image = ImageOps.exif_transpose(source).convert("RGB")
    width, height = image.size
    widths = [w for w in WIDTHS if w < width] + [width]
    for target in widths:
        out = path.with_name(f"{path.stem}-{target}.webp")
        if out.exists() and out.stat().st_mtime >= path.stat().st_mtime:
            continue
        resized = image if target == width else image.resize(
            (target, round(height * target / width)), Image.LANCZOS)
        resized.save(out, "WEBP", quality=QUALITY, method=6)
        print(f"  wrote {out.relative_to(ROOT)} ({out.stat().st_size // 1024} KB)")
    return width, height, widths


def main():
    lines = [
        "# Generated by scripts/build_images.py — do not edit by hand.",
        "# Key: site path of the original; base + \"-<width>.webp\" are the resized copies.",
    ]
    for folder in PHOTO_DIRS:
        for path in sorted((ROOT / folder).rglob("*")):
            if path.suffix.lower() not in (".jpg", ".jpeg", ".png"):
                continue
            print(path.relative_to(ROOT))
            width, height, widths = variants_for(path)
            site_path = "/" + path.relative_to(ROOT).as_posix()
            lines += [
                f'"{site_path}":',
                f"  width: {width}",
                f"  height: {height}",
                f'  base: "{site_path.rsplit(".", 1)[0]}"',
                f"  webp: [{', '.join(str(w) for w in widths)}]",
            ]
    for name in SIZE_ONLY:
        path = ROOT / name
        if path.exists():
            with Image.open(path) as image:
                width, height = image.size
            lines += [f'"/{name}":', f"  width: {width}", f"  height: {height}"]
    (ROOT / "_data" / "images.yml").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("updated _data/images.yml")


if __name__ == "__main__":
    main()
